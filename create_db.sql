-- 4. Проверка: список книг с авторами
-- ============================================================
SELECT table_books.title,
       table_authors.full_name
FROM table_books
         JOIN table_authors_books 
             ON table_authors_books.book_id = table_books.id
         JOIN table_authors 
             ON table_authors.id = table_authors_books.author_id
ORDER BY table_books.id, table_authors.id;

SELECT table_books.title AS title,
       GROUP_CONCAT(table_authors.full_name, ', ') AS authors
FROM table_authors_books 
         JOIN table_books
             ON table_authors_books.book_id = table_books.id
         JOIN table_authors 
             ON table_authors_books.author_id = table_authors.id 
GROUP BY table_books.id, table_books.title;